STRINGS: Mapping[str, Mapping[str, str]] = {"es": ES, "en": EN}


class Translator:
    """``t("key", n=3)`` -> the string of the language, formatted. A missing key is a bug that a
    test finds, but the page still shows the key instead of failing (and instead of formatting
    it)."""

    def __init__(self, language: str) -> None:
        self.language = language if language in STRINGS else DEFAULT_LANGUAGE
        self._strings = STRINGS[self.language]

    def raw(self, key: str) -> str:
        return self._strings.get(key, key)

    def has(self, key: str) -> bool:
        return key in self._strings

    def __call__(self, key: str, **params: Any) -> str:
        """The string of ``key`` formatted with ``params``. A key that does not exist is
        returned as it is and NEVER formatted: some keys are built from text the agent wrote."""
        template = self._strings.get(key)
        if template is None:
            return key
        return template.format(**params)

    def plural(self, key: str, n: int) -> str:
        return self(f"{key}.one" if n == 1 else f"{key}.other", n=n)


def negotiate(header: str | None) -> str:
    """The language from an ``Accept-Language`` header: the first one of ours that it lists
    (ordered by its q values), else the default."""
    if not header:
        return DEFAULT_LANGUAGE
    ranked: list[tuple[float, int, str]] = []
    for position, part in enumerate(header.split(",")):
        tag, _, params = part.strip().partition(";")
        weight = 1.0
        params = params.strip()
        if params.startswith("q="):
            try:
                weight = float(params[2:])
            except ValueError:
                weight = 0.0
        code = tag.strip().lower().split("-")[0]
        if code in STRINGS and weight > 0:
            ranked.append((-weight, position, code))
    return min(ranked)[2] if ranked else DEFAULT_LANGUAGE
